const inr = (n) =>
  "₹" +
  Number(n || 0).toLocaleString("en-IN", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
const fmt = (d) =>
  new Date(d).toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
const esc = (s = "") =>
  String(s).replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c],
  );

export default function invoiceHTML(inv, seller) {
  const rows = inv.lines
    .map(
      (
        l,
        i,
      ) => `<tr><td>${i + 1}</td><td>${esc(l.name)}<small>${l.hsn ? "HSN " + esc(l.hsn) : ""}</small></td>
      <td class="r">${l.qty}</td><td class="r">${inr(l.price)}</td><td class="r">${l.gstRate}%</td><td class="r">${inr(l.taxable)}</td></tr>`,
    )
    .join("");
  const taxRows = inv.isInterState
    ? `<tr><td>IGST</td><td class="r">${inr(inv.igst)}</td></tr>`
    : `<tr><td>CGST</td><td class="r">${inr(inv.cgst)}</td></tr><tr><td>SGST</td><td class="r">${inr(inv.sgst)}</td></tr>`;
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  *{box-sizing:border-box}body{font-family:Helvetica,Arial,sans-serif;color:#111936;margin:0;padding:40px;font-size:13px}
  .top{display:flex;justify-content:space-between;border-bottom:3px solid #3340D8;padding-bottom:18px}
  h1{margin:0;font-size:26px;color:#3340D8}h2{margin:0 0 4px;font-size:18px}.m{color:#5B6485;line-height:1.5}
  .grid{display:flex;justify-content:space-between;margin:24px 0}.grid div{width:48%}
  table{width:100%;border-collapse:collapse}th{background:#F0F2FA;text-align:left;padding:10px;font-size:12px}
  td{padding:10px;border-bottom:1px solid #E3E6EF;vertical-align:top}small{display:block;color:#5B6485}.r{text-align:right}
  .sum{width:280px;margin:20px 0 0 auto}.sum td{border:0;padding:5px 10px}.tot td{font-size:16px;font-weight:700;border-top:2px solid #111936}
  .foot{margin-top:40px;color:#5B6485;font-size:11px;border-top:1px solid #E3E6EF;padding-top:12px}
  .badge{display:inline-block;padding:3px 10px;border-radius:99px;background:#FEF3DC;color:#8A5A00;font-weight:700;font-size:11px}
  </style></head><body>
  <div class="top"><div><h2>${esc(seller.businessName || seller.name)}</h2><div class="m">${esc(seller.address)}<br>${esc(seller.state)}${seller.gstin ? "<br>GSTIN: " + esc(seller.gstin) : ""}${seller.phone ? "<br>" + esc(seller.phone) : ""}</div></div>
  <div class="r"><h1>TAX INVOICE</h1><div class="m"><b>${esc(inv.invoiceNo)}</b><br>Issued: ${fmt(inv.issueDate)}<br>Due: ${fmt(inv.dueDate)}</div></div></div>
  <div class="grid"><div><b>Bill to</b><div class="m">${esc(inv.customerName)}<br>${esc(inv.customerEmail)}<br>${esc(inv.customerState)}${inv.customerGstin ? "<br>GSTIN: " + esc(inv.customerGstin) : ""}</div></div>
  <div class="r"><b>Place of supply</b><div class="m">${esc(inv.customerState)}<br><span class="badge">${inv.isInterState ? "Inter-state · IGST" : "Intra-state · CGST + SGST"}</span></div></div></div>
  <table><thead><tr><th>#</th><th>Item</th><th class="r">Qty</th><th class="r">Rate</th><th class="r">GST</th><th class="r">Taxable value</th></tr></thead><tbody>${rows}</tbody></table>
  <table class="sum"><tr><td>Subtotal</td><td class="r">${inr(inv.subtotal)}</td></tr>${taxRows}<tr class="tot"><td>Total</td><td class="r">${inr(inv.total)}</td></tr></table>
  ${inv.notes ? `<div class="foot"><b>Notes:</b> ${esc(inv.notes)}</div>` : ""}
  <div class="foot">This is a computer-generated invoice. Generated by InvoiceFlow.</div></body></html>`;
}
